#!/usr/bin/env python3
"""Generate gfx-bridge-plan.h from gfx-bridge-plan.bin (2 bridges x 33 little-endian offset/value pairs).

The module embeds exactly the table the userspace gpu-bridge-once replays, so the SHA-256 of the plan is
checked here (host side, at generation time) and recorded in the header.
"""
import hashlib
import struct
import sys
from pathlib import Path

PLAN_SHA = "1c7b3839da2e7aa914a393e914a7a427c12190293ba5d2b50fe06cf4d8df6435"


def render(data: bytes) -> str:
    if hashlib.sha256(data).hexdigest() != PLAN_SHA:
        raise ValueError("bridge plan checksum mismatch")
    if len(data) != 2 * 33 * 8:
        raise ValueError("bridge plan has the wrong size")
    words = struct.unpack("<132I", data)
    out = [f"/* Generated by gen_bridge_header.py from gfx-bridge-plan.bin sha256 {PLAN_SHA}. Do not edit. */",
           "static const u32 bridge_plan[2][33][2] = {"]
    for table in range(2):
        out.append("\t{")
        for i in range(33):
            offset, value = words[(table * 33 + i) * 2:(table * 33 + i) * 2 + 2]
            expected = 0x18 if i == 0 else 0x40000 + (i - 1) * 4
            if offset != expected:
                raise ValueError(f"unexpected offset 0x{offset:x} at table {table} entry {i}")
            out.append(f"\t\t{{ 0x{offset:05x}, 0x{value:08x} }},")
        out.append("\t},")
    out.append("};")
    return "\n".join(out) + "\n"


if __name__ == "__main__":
    plan, header = Path(sys.argv[1]), Path(sys.argv[2])
    header.write_text(render(plan.read_bytes()))
    print(f"wrote {header}")
